export type TranslationKey = keyof typeof messages.vi;
type TranslationValues = Record<string, string | number>;

interface I18nContextValue {
  language: LanguagePreference;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ language, children }: { language: LanguagePreference; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = (key: TranslationKey, values?: TranslationValues) => {
    const template = messages[language][key] ?? messages.vi[key];
    return values
      ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
      : template;
  };

  return <I18nContext.Provider value={{ language, t }}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useTranslation must be used within I18nProvider.");
  return context;
}
